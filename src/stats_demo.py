import numpy as np
import matplotlib.pyplot as plt

# ==========================================================
# МОДУЛЬ 1: Генерация тестовых эмбеддингов
# ==========================================================

print("🔬 Генерация тестовых данных для HR-системы")
print("=" * 60)

# Генерируем эмбеддинги кандидатов (каждый кандидат - точка в пространстве)
# В реальности эмбеддинги имеют 384+ измерений, для теста берем 1 измерение
n_candidates = 1000
embeddings = np.random.normal(0, 1, n_candidates)
print(f"✅ Сгенерировано {len(embeddings)} тестовых эмбеддингов")

# ==========================================================
# МОДУЛЬ 2: Нормализация данных
# ==========================================================

print("\n📊 Статистика по кандидатам")
print("-" * 40)

mean_val = np.mean(embeddings)
std_val = np.std(embeddings)
median_val = np.median(embeddings)

print(f"Среднее (центр распределения кандидатов): {mean_val:.3f}")
print(f"Стандартное отклонение (разброс кандидатов): {std_val:.3f}")
print(f"Медиана (типичный кандидат, устойчив к выбросам): {median_val:.3f}")

# ==========================================================
# МОДУЛЬ 3: Анализ схожести кандидатов
# ==========================================================

print("\n🎯 Анализ схожести кандидатов с вакансией")
print("-" * 40)

# Представим, что у нас есть идеальный кандидат (эмбеддинг вакансии)
ideal_candidate = 0.5

# Считаем схожесть (чем ближе к 0, тем лучше)
similarities = 1 - np.abs(embeddings - ideal_candidate)
similarities = np.clip(similarities, 0, 1)  # ограничиваем от 0 до 1

print(f"Средняя схожесть всех кандидатов: {np.mean(similarities):.3f}")
print(f"Максимальная схожесть: {np.max(similarities):.3f}")
print(f"Топ-5% кандидатов имеют схожесть > {np.percentile(similarities, 95):.3f}")

# ==========================================================
# МОДУЛЬ 4: Правило 68-95-99.7 (для анализа скоринга)
# ==========================================================

print("\n📈 Распределение оценок кандидатов")
print("-" * 40)

# Сколько кандидатов попадают в интервал [mean - std, mean + std]
lower = mean_val - std_val
upper = mean_val + std_val
within_1std = np.sum((embeddings >= lower) & (embeddings <= upper))
percent_1std = within_1std / n_candidates * 100

print(f"Кандидаты в пределах 1σ от среднего: {percent_1std:.1f}% (теория: ~68%)")

# ==========================================================
# МОДУЛЬ 5: Обнаружение выбросов (аномальных кандидатов)
# ==========================================================

print("\n🚨 Поиск аномальных кандидатов")
print("-" * 40)

# Добавляем явного выброса (кандидат с нереальными параметрами)
embeddings_with_outlier = np.append(embeddings, 10)
outlier_median = np.median(embeddings_with_outlier)
outlier_mean = np.mean(embeddings_with_outlier)

print(f"Медиана с выбросом: {outlier_median:.3f} (устойчива)")
print(f"Среднее с выбросом: {outlier_mean:.3f} (сильно изменилось)")

# Находим кандидатов с аномальными эмбеддингами (>3 стандартных отклонений)
anomalies = embeddings[np.abs(embeddings - mean_val) > 3 * std_val]
print(f"Найдено аномальных кандидатов: {len(anomalies)}")

# ==========================================================
# МОДУЛЬ 6: Визуализация распределения
# ==========================================================

print("\n📊 Построение графиков...")

plt.figure(figsize=(12, 5))

# График 1: Распределение эмбеддингов кандидатов
plt.subplot(1, 2, 1)
plt.hist(embeddings, bins=30, color='skyblue', edgecolor='black')
plt.axvline(mean_val, color='red', linestyle='--', label=f'Среднее ({mean_val:.2f})')
plt.axvline(median_val, color='green', linestyle='--', label=f'Медиана ({median_val:.2f})')
plt.title('Распределение кандидатов в семантическом пространстве')
plt.xlabel('Эмбеддинг (позиция в пространстве)')
plt.ylabel('Количество кандидатов')
plt.legend()

# График 2: Распределение схожести с вакансией
plt.subplot(1, 2, 2)
plt.hist(similarities, bins=30, color='lightgreen', edgecolor='black')
plt.axvline(np.mean(similarities), color='red', linestyle='--', label=f'Средняя схожесть')
plt.title('Распределение схожести кандидатов с вакансией')
plt.xlabel('Схожесть (0-1)')
plt.ylabel('Количество кандидатов')
plt.legend()

plt.tight_layout()
plt.show()

# ==========================================================
# МОДУЛЬ 7: Автоматические проверки
# ==========================================================

print("\n🧪 Запуск автоматических проверок...")
print("-" * 40)

assert len(embeddings) == n_candidates, "Неверное количество кандидатов"
assert isinstance(mean_val, float), "Среднее должно быть float"
assert isinstance(std_val, float), "Стандартное отклонение должно быть float"
assert 0 <= np.mean(similarities) <= 1, "Схожесть должна быть от 0 до 1"

print("✅ Все тесты пройдены! Система работает корректно")
print("=" * 60)
print("🎯 Выводы для диплома:")
print("  • Статистика помогает понять распределение кандидатов")
print("  • Медиана устойчива к выбросам (важно для зарплат)")
print("  • Правило 68-95-99.7 работает для нормальных распределений")
print("  • Визуализация нужна для интерпретируемости")