# Базовые операции с матрицами для диплома

import numpy as np

# Ячейка 1 — создаём матрицу (данные кандидатов)
X = np.array([
    [1, 2],
    [3, 4],
    [5, 6]
])

# Ячейка 2 — размер матрицы
rows, cols = X.shape

# Ячейка 3 — создаём вектор весов
w = np.array([10, 1])

# Ячейка 4 — умножение матрицы на вектор (получаем оценки кандидатов)
result = X @ w